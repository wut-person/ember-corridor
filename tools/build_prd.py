def set_run_font(run, size=None, bold=None, italic=None, color=None, font=None,
                 east=None):
    """同时设置西文与东亚字体，避免中文回退成默认宋体"""
    f = font or EN_FONT
    run.font.name = f
    rpr = run._element.get_or_add_rPr()
    rf = rpr.find(qn('w:rFonts'))
    if rf is None:
        rf = OxmlElement('w:rFonts')
        rpr.append(rf)
    rf.set(qn('w:ascii'), f)
    rf.set(qn('w:hAnsi'), f)
    rf.set(qn('w:eastAsia'), east or CN_FONT)
    if size is not None:
        run.font.size = Pt(size)
    if bold is not None:
        run.font.bold = bold
    if italic is not None:
        run.font.italic = italic
    if color is not None:
        run.font.color.rgb = color
    return run


def para(doc, text="", size=10.5, bold=False, italic=False, color=None,
         align=None, space_after=6, space_before=0, indent=None, style=None):
    p = doc.add_paragraph(style=style)
    if align is not None:
        p.alignment = align
    pf = p.paragraph_format
    pf.space_after = Pt(space_after)
    pf.space_before = Pt(space_before)
    pf.line_spacing = 1.4
    if indent is not None:
        pf.left_indent = Cm(indent)
    if text:
        set_run_font(p.add_run(text), size=size, bold=bold, italic=italic, color=color)
    return p


def rich(doc, segments, size=10.5, align=None, space_after=6, indent=None):
    """segments: [(text, bold, color)] 便于混排强调"""
    p = doc.add_paragraph()
    if align is not None:
        p.alignment = align
    pf = p.paragraph_format
    pf.space_after = Pt(space_after)
    pf.line_spacing = 1.4
    if indent is not None:
        pf.left_indent = Cm(indent)
    for seg in segments:
        text, bold = seg[0], seg[1]
        color = seg[2] if len(seg) > 2 else None
        set_run_font(p.add_run(text), size=size, bold=bold, color=color)
    return p


def heading(doc, text, level):
    sizes = {1: 15, 2: 12.5, 3: 11}
    h = doc.add_heading(level=level)
    h.paragraph_format.space_before = Pt(14 if level == 1 else 10)
    h.paragraph_format.space_after = Pt(6)
    h.paragraph_format.keep_with_next = True
    set_run_font(h.add_run(text), size=sizes.get(level, 11), bold=True,
                 color=ACCENT if level <= 2 else RGBColor(0x33, 0x33, 0x33))
    return h


def shade(cell, hex_color):
    tcpr = cell._tc.get_or_add_tcPr()
    el = OxmlElement('w:shd')
    el.set(qn('w:val'), 'clear')
    el.set(qn('w:color'), 'auto')
    el.set(qn('w:fill'), hex_color)
    tcpr.append(el)


def set_cell_margins(t, left=70, right=70, top=30, bottom=30):
    """单元格内边距（twips），用于估算可用文字宽度"""
    tblPr = t._tbl.tblPr
    mar = OxmlElement('w:tblCellMar')
    for tag, val in (('w:top', top), ('w:left', left), ('w:bottom', bottom), ('w:right', right)):
        el = OxmlElement(tag)
        el.set(qn('w:w'), str(val))
        el.set(qn('w:type'), 'dxa')
        mar.append(el)
    tblPr.append(mar)


def set_fixed_layout(t, widths_cm):
    """固定列宽：写 tblLayout=fixed + tblW + tblGrid + 单元格宽度，Word/LO 才会严格遵守"""
    tblPr = t._tbl.tblPr
    layout = tblPr.find(qn('w:tblLayout'))
    if layout is None:
        layout = OxmlElement('w:tblLayout')
        tblPr.append(layout)
    layout.set(qn('w:type'), 'fixed')
    total_tw = int(round(sum(widths_cm) * 567))
    tw = tblPr.find(qn('w:tblW'))
    if tw is None:
        tw = OxmlElement('w:tblW')
        tblPr.append(tw)
    tw.set(qn('w:type'), 'dxa')
    tw.set(qn('w:w'), str(total_tw))
    grid = t._tbl.find(qn('w:tblGrid'))
    if grid is not None:
        t._tbl.remove(grid)
    grid = OxmlElement('w:tblGrid')
    for w in widths_cm:
        gc = OxmlElement('w:gridCol')
        gc.set(qn('w:w'), str(int(round(w * 567))))
        grid.append(gc)
    t._tbl.insert(list(t._tbl).index(tblPr) + 1, grid)
    for row in t.rows:
        for i, w in enumerate(widths_cm):
            if i < len(row.cells):
                row.cells[i].width = Cm(w)


def disp_len(s):
    """中文按 2 个西文宽度计算"""
    n = 0
    for ch in str(s):
        n += 2 if ord(ch) > 0x2E7F else 1
    return n


def fit_widths(headers, rows, weights, total=13.0, font_size=9):
    """按内容长度分配列宽并保证最小列宽，最终总宽精确等于 total（厘米）"""
    nat = []
    for i in range(len(headers)):
        m = disp_len(headers[i])
        for r in rows:
            m = max(m, disp_len(r[i]) if i < len(r) else 0)
        nat.append(max(m, 6))
    pad = 0.34                                   # 左右内边距 + 边框
    need = [n * font_size * 0.021 + pad for n in nat]
    minw = 1.55                                  # 最少容纳约 3 个汉字
    w = [max(n, minw) for n in need]             # 先满足内容与最小值
    s = total / sum(w)
    # 必须缩小时，只从“超过最小宽度”的列里收，绝不把列压到最小值以下
    for _ in range(40):
        tot = sum(w)
        if abs(tot - total) < 0.02:
            break
        if tot > total:
            over = tot - total
            flex = [max(0.0, x - minw) for x in w]
            fs = sum(flex)
            if fs <= 0.01:
                break
            k = min(1.0, over / fs)
            w = [x - f * k for x, f in zip(w, flex)]
        else:                                     # 富余宽度按内容比例分配给可伸展的列
            gap = total - tot
            stretch = [x - minw for x in w]
            ss = sum(stretch) or 1.0
            w = [x + gap * (st / ss) for x, st in zip(w, stretch)]
    return [round(x, 2) for x in w]


def W(weights, font_size=9):
    """用法：widths=W([3, 5, 8])；真正建表时按内容自适应分配列宽，保证不超出页面"""
    return lambda headers, rows: fit_widths(headers, rows, weights, total=13.0, font_size=font_size)


def table(doc, headers, rows, widths=None, font_size=9, header_fill="F2E2D6"):
    if callable(widths):
        widths = widths(headers, rows)
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    hdr = t.rows[0].cells
    for i, htext in enumerate(headers):
        hdr[i].text = ''
        p = hdr[i].paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.space_after = Pt(2)
        p.paragraph_format.line_spacing = 1.15
        set_run_font(p.add_run(htext), size=font_size, bold=True)
        shade(hdr[i], header_fill)
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = ''
            p = cells[i].paragraphs[0]
            p.paragraph_format.space_after = Pt(2)
            p.paragraph_format.line_spacing = 1.2
            txt = '' if val is None else str(val)
            set_run_font(p.add_run(txt), size=font_size)
    if widths:
        set_fixed_layout(t, widths)
    set_cell_margins(t)
    return t


def bullets(doc, items, size=10.5, indent=0.6):
    for it in items:
        if isinstance(it, tuple):
            p = rich(doc, [(it[0], True), (it[1], False)], size=size, indent=indent)
            p.paragraph_format.space_after = Pt(3)
        else:
            p = para(doc, "· " + it, size=size, indent=indent, space_after=3)
    return doc


